-- ALLERGY-CLASS EXAMPLES (illustrative only -- NOT executable inserts;
-- patient_allergies is patient-specific and populated via the Phase-2 API,
-- never seeded as reference data)
--
-- These show how prescription_safety.check_allergy_conflicts's exact,
-- case-insensitive match against drug.name / drug.generic_name /
-- drug.interaction_class is expected to behave against the drugs seeded
-- above, and where its documented false-negative gap shows up:
--
--   1. patient_allergies.substance = 'Amoxicillin'
--      -> matches Amoxil (generic_name = 'Amoxicillin') exactly. Caught.
--
--   2. patient_allergies.substance = 'Penicillin'
--      -> does NOT match Amoxil or Augmentin: neither drug's name,
--         generic_name, or interaction_class ('beta-lactam') is literally
--         the string 'Penicillin'. This is the documented gap: a clinician
--         who records a class-level allergy using a different word than
--         what's in interaction_class will not be caught by this checker.
--         See prescription_safety.py's module docstring.
--
--   3. patient_allergies.substance = 'nsaid'
--      -> matches Bayer Aspirin, Advil, and Aleve (all have
--         interaction_class = 'nsaid'), case-insensitively. This is the
--         one path where a class-level allergy IS caught -- because this
--         seed data's interaction_class happens to equal the substance
--         string the clinician would plausibly type.
-- ============================================================================
