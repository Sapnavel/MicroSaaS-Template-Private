-- ============================================================================
-- CLINICAL REFERENCE SEED DATA -- drugs & drug_interactions
--
-- SCOPE LIMITATION: this is a small, illustrative scaffold dataset for
-- development/testing of the Smart Prescription Engine's safety checker
-- (backend/app/services/prescription_safety.py). It is NOT a clinically
-- complete or validated drug/interaction database, and must never be
-- presented or relied upon as one. A real deployment must integrate a
-- licensed drug/interaction reference source -- e.g. RxNorm, First
-- Databank (FDB), DrugBank, or an equivalent -- in place of (or feeding
-- into) the `drugs`/`drug_interactions` tables this file seeds.
--
-- NOT auto-run: unlike database/schema.sql, this file is NOT picked up by
-- the docker-entrypoint-initdb.d mechanism (that only runs scripts present
-- at container FIRST INIT, and only for schema/bootstrap files placed
-- there deliberately). This is reference/lookup data, not schema, and is
-- meant to be re-run independently of container lifecycle (e.g. to reset
-- or refresh reference data without recreating the database). Apply it
-- manually, after schema.sql, e.g.:
--
--   psql "$DATABASE_URL" -f database/schema.sql
--   psql "$DATABASE_URL" -f database/seed_clinical_reference_data.sql
--
-- Idempotency: this file does NOT guard against re-running (no
-- ON CONFLICT / DELETE-first). Running it twice against the same database
-- will insert duplicate drug/interaction rows (drugs.id is a fresh
-- gen_random_uuid() per run, so there's no natural key to upsert against).
-- For a fresh test/dev database this is fine -- run once after schema.sql.
-- If you need idempotent re-seeding, TRUNCATE drug_interactions, drugs
-- first (in that order, drug_interactions references drugs).
--
-- Patient allergies are NOT seeded here: allergies are patient-specific
-- clinical data recorded via the Phase-2 API
-- (POST /api/v1/patients/{patient_id}/allergies), not reference data. See
-- the "ALLERGY-CLASS EXAMPLES" comment block at the bottom of this file for
-- illustrative (not executable) examples of how allergy substances are
-- expected to relate to the seeded drugs below, for manual testing.
-- ============================================================================

