-- ----------------------------------------------------------------------------
-- DRUG INTERACTIONS -- a handful of well-known, textbook pairs.
-- Severity vocabulary matches prescription_safety.py's classification
-- table: contraindicated | major | moderate | minor.
--
-- NOTE: drug_interactions has no natural key beyond the (drug_a_id,
-- drug_b_id) pair, and the drug ids above are freshly generated by this
-- same script run -- so the interactions below are wired up via name
-- lookups in the same statement (subqueries), not hardcoded UUIDs, which
-- would be meaningless across runs.
-- ----------------------------------------------------------------------------
INSERT INTO drug_interactions (drug_a_id, drug_b_id, severity, description)
SELECT w.id, a.id, 'major', 'Increased bleeding risk: NSAID displaces warfarin protein binding and impairs platelet function.'
FROM drugs w, drugs a
WHERE w.generic_name = 'Warfarin' AND a.generic_name = 'Aspirin'
ON CONFLICT DO NOTHING;

